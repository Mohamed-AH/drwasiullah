#!/usr/bin/env node
/* Content database tool (Cloudflare D1 = SQLite). Phase 1 of docs/admin-portal-spec.md. No dependencies (Node 22 `node:sqlite`).

   node scripts/db.mjs seed   [--site site] [--out db/seed.sql]     site data files -> SQL that fills an EMPTY or existing D1 (it clears the content tables first)
   node scripts/db.mjs export --out DIR [--from-sql dump.sql | --db file.sqlite] [--all] [--only data/library.json,...]
                                                                    database -> the same data files (published rows only, unless --all)
   node scripts/db.mjs mirror-catalogue [--site site] [--out db/mirror.sql]   SQL that refreshes the database's copy of the YouTube catalogue after the daily sync
   node scripts/db.mjs verify [--site site]                         seed -> scratch database -> export -> byte-compare with the files in git

   `export --from-sql` reads the dump written by `wrangler d1 export`, so the same code serves the nightly backup and (later) Publish. */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS = path.join(ROOT, "db", "migrations");

/* which data file holds what. `lists`: top-level arrays stored as rows; `rows` tables; everything else lives in `docs`. */
const FILES = [
  { name: "catalogue.json",     origin: "catalogue", lists: ["series", "lessons"], meta: "catalogue.meta" },
  { name: "data/library.json",  origin: "library",   lists: ["series", "lessons", "books"] },
  { name: "data/makkah.json",   origin: "makkah",    lists: ["series", "lessons"] },
  { name: "data/haram.json",    origin: "haram",     lists: ["series", "lessons"] },
  { name: "data/media.json",    map: true },
  { name: "data/schedule.json", doc: "schedule" },
  { name: "data/bio.json",      doc: "bio" },
  { name: "data/order.json",     order: true },               // saved display order of series (phase 4c); table `series_order`
  { name: "data/overrides.json", overrides: true },          // editors' patches on the YouTube catalogue (phase 4b); table `overrides`
];
const TABLE = { series: "series", lessons: "lessons", books: "books" };

const q = v => v == null ? "NULL" : typeof v === "number" ? String(v) : "'" + String(v).replace(/'/g, "''") + "'";
const js = v => JSON.stringify(v);
const int = v => Number.isInteger(v) ? v : null;

function layout(text) {                       // how the file was written: indent width (null = minified) and trailing newline
  const m = /^\{\r?\n( +)"/.exec(text);   // files checked out on Windows may have CRLF line ends
  return { indent: m ? m[1].length : null, nl: text.endsWith("\n") ? 1 : 0 };
}
const render = (obj, f) => JSON.stringify(obj, null, f.indent ?? undefined) + (f.trailing_nl ? "\n" : "");

/* ---------- seed ---------- */
function makeInserter(out) {
  return (table, cols, rows) => {                               // batches stay far below D1's 100 KB-per-statement limit
    let batch = [], size = 0;
    const flush = () => { if (batch.length) out.push(`INSERT INTO ${table} (${cols.join(",")}) VALUES\n${batch.join(",\n")};`); batch = []; size = 0; };
    for (const r of rows) {
      const v = "(" + r.map(q).join(",") + ")";
      if (size + v.length > 30000) flush();
      batch.push(v); size += v.length;
    }
    flush();
  };
}
const seriesRow = (s, origin, i) => [s.id, origin, i, s.sec ?? null, s.title ?? "", "published", js(s)];
const lessonRow = (l, origin, i) => [l.id, origin, i, l.series ?? null, l.kind ?? (origin === "catalogue" ? "video" : null), int(l.n), l.section ?? null, "published", js(l)];

/* The daily YouTube sync still owns site/catalogue.json. After it commits, this SQL refreshes the database's copy of those rows (origin "catalogue"),
   so the portal can list and edit them; editors' patches live in their own table (overrides) and are never touched here. Atomic when run as one file. */
export function mirrorCatalogueSql(siteDir) {
  const cat = JSON.parse(fs.readFileSync(path.join(siteDir, "catalogue.json"), "utf8"));
  const out = ["-- generated by scripts/db.mjs mirror-catalogue: replaces the database's copy of the YouTube catalogue (editors' patches in `overrides` are untouched)"];
  const insert = makeInserter(out);
  out.push("DELETE FROM lessons WHERE origin = 'catalogue';", "DELETE FROM series WHERE origin = 'catalogue';");
  insert("series", ["id", "origin", "pos", "sec", "title", "status", "data"], cat.series.map((x, i) => seriesRow(x, "catalogue", i)));
  insert("lessons", ["id", "origin", "pos", "series_id", "kind", "n", "section", "status", "data"], cat.lessons.map((x, i) => lessonRow(x, "catalogue", i)));
  const meta = {}; for (const k of Object.keys(cat)) if (k !== "series" && k !== "lessons") meta[k] = cat[k];
  out.push(`INSERT OR REPLACE INTO docs (name, data) VALUES (${q("catalogue.meta")}, ${q(js(meta))});`);
  return out.join("\n") + "\n";
}

export function seedSql(siteDir) {
  const out = [];
  const insert = makeInserter(out);
  out.push("-- generated by scripts/db.mjs seed; clears and refills the content tables (users, audit_log and stats_daily are NOT touched).");
  out.push("-- WARNING: once the admin portal is in use, DO NOT run this on the live database: it would erase edits that were saved but not yet published.");
  for (const t of ["series", "lessons", "books", "media", "docs", "files", "overrides", "series_order"]) out.push(`DELETE FROM ${t};`);
  const rows = { series: [], lessons: [], books: [], media: [], docs: [], files: [], overrides: [], series_order: [] };
  for (const f of FILES) {
    const file = path.join(siteDir, f.name);
    if (!fs.existsSync(file)) continue;
    const text = fs.readFileSync(file, "utf8"), obj = JSON.parse(text), lay = layout(text);
    rows.files.push([f.name, lay.indent, lay.nl, js(f.map || f.doc || f.overrides || f.order ? [] : Object.keys(obj))]);   // key order only matters for files made of lists
    if (f.order) {
      for (const [sid, ids] of Object.entries(obj)) rows.series_order.push([sid, js(ids)]);
    } else if (f.overrides) {
      for (const kind of ["lessons", "series"]) for (const [id, patch] of Object.entries(obj[kind] || {})) rows.overrides.push([kind === "lessons" ? "lesson" : "series", id, js(patch)]);
    } else if (f.map) {
      Object.entries(obj).forEach(([src, v], i) => rows.media.push([src, i, js(v)]));
    } else if (f.doc) {
      rows.docs.push([f.doc, js(obj)]);
    } else {
      const meta = {};
      for (const k of Object.keys(obj)) if (!f.lists.includes(k)) meta[k] = obj[k];
      if (f.meta) rows.docs.push([f.meta, js(meta)]);
      else if (Object.keys(meta).length) throw new Error(`${f.name}: unexpected top-level keys ${Object.keys(meta)}`);
      (obj.series || []).forEach((x, i) => rows.series.push(seriesRow(x, f.origin, i)));
      (obj.lessons || []).forEach((x, i) => rows.lessons.push(lessonRow(x, f.origin, i)));
      (obj.books || []).forEach((b, i) => rows.books.push([b.id, f.origin, i, b.title ?? "", "published", js(b)]));
    }
  }
  insert("series", ["id", "origin", "pos", "sec", "title", "status", "data"], rows.series);
  insert("lessons", ["id", "origin", "pos", "series_id", "kind", "n", "section", "status", "data"], rows.lessons);
  insert("books", ["id", "origin", "pos", "title", "status", "data"], rows.books);
  insert("media", ["src", "pos", "data"], rows.media);
  insert("overrides", ["kind", "id", "patch"], rows.overrides);
  insert("series_order", ["series_id", "ids"], rows.series_order);
  insert("docs", ["name", "data"], rows.docs);
  insert("files", ["name", "indent", "trailing_nl", "keys"], rows.files);
  return out.join("\n") + "\n";
}

/* ---------- export ---------- */
export function exportFiles(db, outDir, { all = false, only = null } = {}) {
  const written = [];
  /* what ships to the site: published rows only; a lesson also needs its series to be published (hiding a series hides its lessons),
     and a series with no published lesson is left out (an empty shelf book makes no sense). `all` = everything (backups). */
  const where = {
    series: all ? "" : "WHERE status = 'published' AND EXISTS (SELECT 1 FROM lessons l WHERE l.series_id = series.id AND l.status = 'published')",
    lessons: all ? "" : "WHERE status = 'published' AND (series_id IS NULL OR series_id IN (SELECT id FROM series WHERE status = 'published'))",
    books: all ? "" : "WHERE status = 'published'",
  };
  const get = (sql, ...a) => db.prepare(sql).all(...a);
  const docs = Object.fromEntries(get("SELECT name, data FROM docs").map(r => [r.name, JSON.parse(r.data)]));
  const lay = Object.fromEntries(get("SELECT * FROM files").map(r => [r.name, r]));
  for (const f of FILES) {
    const l = lay[f.name] || (f.overrides || f.order ? { indent: null, trailing_nl: 0, keys: "[]" } : null);   // overrides.json / order.json may not have existed in the seed
    if (!l || (only && !only.includes(f.name))) continue;                  // file did not exist in the seed / not asked for
    const keys = JSON.parse(l.keys);
    let obj;
    if (f.order) {
      obj = {};
      for (const r of get("SELECT series_id, ids FROM series_order ORDER BY series_id")) obj[r.series_id] = JSON.parse(r.ids);
    } else if (f.overrides) {
      obj = { lessons: {}, series: {} };
      for (const r of get("SELECT kind, id, patch FROM overrides ORDER BY kind, id")) obj[r.kind === "lesson" ? "lessons" : "series"][r.id] = JSON.parse(r.patch);
    } else if (f.map) obj = Object.fromEntries(get("SELECT src, data FROM media ORDER BY pos").map(r => [r.src, JSON.parse(r.data)]));
    else if (f.doc) obj = docs[f.doc];
    else {
      const meta = f.meta ? docs[f.meta] : {};
      obj = {};
      for (const k of keys) obj[k] = f.lists.includes(k)
        ? get(`SELECT data FROM ${TABLE[k]} ${where[k] ? where[k] + " AND" : "WHERE"} origin = ? ORDER BY pos`, f.origin).map(r => JSON.parse(r.data))
        : meta[k];
    }
    const file = path.join(outDir, f.name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, render(obj, l));
    written.push(f.name);
  }
  return written;
}

/* ---------- plumbing ---------- */
function scratchDb() {
  const db = new DatabaseSync(":memory:");
  for (const m of fs.readdirSync(MIGRATIONS).filter(x => x.endsWith(".sql")).sort()) db.exec(fs.readFileSync(path.join(MIGRATIONS, m), "utf8"));
  return db;
}
const arg = (name, dflt) => { const i = process.argv.indexOf("--" + name); return i < 0 ? dflt : process.argv[i + 1]; };
const flag = name => process.argv.includes("--" + name);

function verify(siteDir) {
  const db = scratchDb();
  db.exec(seedSql(siteDir));
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "dbverify-"));
  const written = exportFiles(db, tmp);
  let bad = 0;
  for (const name of written) {
    const EMPTY = { "data/overrides.json": '{"lessons":{},"series":{}}', "data/order.json": "{}" };
    if (EMPTY[name] && !fs.existsSync(path.join(siteDir, name))) {                           // none yet: the export must be the empty document
      const same = fs.readFileSync(path.join(tmp, name), "utf8") === EMPTY[name];
      if (!same) bad++;
      console.log(`${same ? "ok  " : "DIFF"} ${name} (empty, no source file)`);
      continue;
    }
    const a = Buffer.from(fs.readFileSync(path.join(siteDir, name), "utf8").replace(/\r\n/g, "\n")), b = fs.readFileSync(path.join(tmp, name));   // a Windows checkout may have CRLF: line ends are not content
    const same = a.equals(b);
    if (!same) bad++;
    console.log(`${same ? "ok  " : "DIFF"} ${name} (${a.length} bytes)`);
  }
  const c = t => db.prepare(`SELECT COUNT(*) n FROM ${t}`).get().n;
  console.log(`rows: series ${c("series")}, lessons ${c("lessons")}, books ${c("books")}, media ${c("media")}, docs ${c("docs")}`);
  fs.rmSync(tmp, { recursive: true, force: true });
  if (bad || written.filter(n => !["data/overrides.json", "data/order.json"].includes(n) || fs.existsSync(path.join(siteDir, n))).length !== FILES.filter(f => fs.existsSync(path.join(siteDir, f.name))).length) { console.error(`!! ${bad} file(s) differ`); process.exit(1); }
  console.log("parity ok: the database reproduces every data file byte for byte");
}

const cmd = process.argv[2];
if (cmd === "seed") {
  const site = path.resolve(arg("site", path.join(ROOT, "site"))), out = path.resolve(arg("out", path.join(ROOT, "db", "seed.sql")));
  const sql = seedSql(site); fs.writeFileSync(out, sql);
  console.log(`wrote ${out} (${(sql.length / 1e6).toFixed(2)} MB, ${sql.split("\nINSERT").length - 1} INSERT statements)`);
} else if (cmd === "export") {
  const outDir = arg("out"); if (!outDir) { console.error("--out DIR is required"); process.exit(2); }
  let db;
  if (arg("db")) db = new DatabaseSync(arg("db"), { readOnly: true });
  else if (arg("from-sql")) { db = new DatabaseSync(":memory:"); db.exec(fs.readFileSync(arg("from-sql"), "utf8")); }
  else { console.error("give --db file.sqlite or --from-sql dump.sql"); process.exit(2); }
  const w = exportFiles(db, path.resolve(outDir), { all: flag("all"), only: arg("only") ? arg("only").split(",") : null });
  console.log(`wrote ${w.length} files to ${outDir}: ${w.join(", ")}`);
} else if (cmd === "mirror-catalogue") {
  const site = path.resolve(arg("site", path.join(ROOT, "site"))), out = path.resolve(arg("out", path.join(ROOT, "db", "mirror.sql")));
  fs.writeFileSync(out, mirrorCatalogueSql(site)); console.log(`wrote ${out}`);
} else if (cmd === "verify") {
  verify(path.resolve(arg("site", path.join(ROOT, "site"))));
} else {
  console.error("usage: node scripts/db.mjs seed | export | verify   (see the header of this file)");
  process.exit(2);
}
